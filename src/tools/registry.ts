export function getTool(slug: string): ToolMeta | undefined {
  return tools.find((t) => t.slug === slug)
}

export function getCategory(id: CategoryId): ToolCategory {
  // Categories are a closed set; every ToolMeta.category is a CategoryId.
  return categories.find((c) => c.id === id) as ToolCategory
}

export function toolsByCategory(id: CategoryId): ToolMeta[] {
  return tools.filter((t) => t.category === id)
}
