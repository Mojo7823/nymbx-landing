export type ToolBadge = 'client-side' | 'server-assisted'
export type ToolStatus = 'available' | 'coming-soon'

export type CategoryId =
  'markdown' | 'image' | 'files' | 'pdf-office' | 'converters' | 'text-dev' | 'security'

export interface ToolCategory {
  id: CategoryId
  name: string
  icon: LucideIcon
}

export interface ToolMeta {
  /** Route slug: `/tools/<slug>` and `src/tools/<slug>/`. */
  slug: string
  name: string
  description: string
  category: CategoryId
  badge: ToolBadge
  status: ToolStatus
  /** Phase number in PLAN.md — build order reference only. */
  phase: number
  icon: LucideIcon
}

